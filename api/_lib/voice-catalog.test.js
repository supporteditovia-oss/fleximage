const { describe, it } = require("node:test");
const assert = require("node:assert/strict");
const {
  buildCatalogSampleLine,
  clampTtsSpeed,
  isValidFishReferenceId,
  resolveCatalogTtsSpeed,
  unifiedPreviewCacheKey,
} = require("./voice-catalog");

describe("voice-catalog", () => {
  it("uses intro sample line per voice", () => {
    assert.match(buildCatalogSampleLine("Maes", "fr"), /Maes/i);
    assert.match(buildCatalogSampleLine("Maes", "fr"), /LuxeFlexIA/i);
    assert.match(buildCatalogSampleLine("Maes", "en"), /generated by LuxeFlexIA/i);
    assert.match(buildCatalogSampleLine("Maes", "es"), /generado por LuxeFlexIA/i);
  });

  it("validates fish reference ids", () => {
    assert.equal(
      isValidFishReferenceId("6be490a175744894826dd464cf3a5004"),
      true,
    );
    assert.equal(isValidFishReferenceId("invalid"), false);
  });

  it("builds stable cache keys", () => {
    assert.equal(
      unifiedPreviewCacheKey("6BE490A175744894826DD464CF3A5004", "fr"),
      "voice-catalog/unified/v6/fr/6be490a175744894826dd464cf3a5004.mp3",
    );
  });

  it("resolves per-voice Fish TTS speed from catalog rate", () => {
    assert.equal(
      resolveCatalogTtsSpeed("3cfa191ad09b4cfea8e4eebc4c31c923"),
      1.02,
    );
    assert.equal(
      resolveCatalogTtsSpeed("22b7c6809d5d405aa6a5ae2402272b53"),
      0.84,
    );
    assert.equal(resolveCatalogTtsSpeed("not-a-catalog-id"), null);
  });

  it("clamps tts speed to safe bounds", () => {
    assert.equal(clampTtsSpeed(2), 1.35);
    assert.equal(clampTtsSpeed(0.2), 0.65);
  });

  it("prefers clonage catalogue rate over I2V when fish id is shared", () => {
    assert.equal(
      resolveCatalogTtsSpeed("690813f2df56491b82ee02a22d1c67fd"),
      1,
    );
  });

  it("PLK — studio parity preview = génération", () => {
    const {
      resolveCatalogPreviewTtsSpeed,
      resolveCatalogStudioSynth,
    } = require("./voice-catalog");
    const fish = "c9188f639648467f8f1c513b0dbac9f7";
    const studio = resolveCatalogStudioSynth(fish);
    assert.equal(resolveCatalogPreviewTtsSpeed(fish), 0.96);
    assert.equal(studio.speed, 0.96);
    assert.equal(studio.catalogFastFlow, false);
  });

  it("Jul — spokenName Joul dans studio synth", () => {
    const { resolveCatalogStudioSynth } = require("./voice-catalog");
    const jul = resolveCatalogStudioSynth("66754cdcb9554e62bdff1ab6446dc78d");
    assert.equal(jul.spokenName, "Joul");
  });
});
