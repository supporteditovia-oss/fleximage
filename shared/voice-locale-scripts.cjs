/** Scripts voix landing + catalogue — FR / EN / ES (partagé client + API). */

const LOCALES = ["fr", "en", "es"];

function normalizeVoiceLocale(value) {
  const raw = String(value || "")
    .trim()
    .toLowerCase()
    .split("-")[0];
  return LOCALES.includes(raw) ? raw : "fr";
}

const LANDING_NATURAL_MALE = {
  fr: "Bonjour, voici une voix masculine naturelle — générée par LuxeFlexIA.",
  en: "Hello, this is a natural male voice — generated by LuxeFlexIA.",
  es: "Hola, esta es una voz masculina natural — generada por LuxeFlexIA.",
};

const LANDING_NATURAL_FEMALE = {
  fr: "Bonjour, voici une voix féminine naturelle — générée par LuxeFlexIA.",
  en: "Hello, this is a natural female voice — generated by LuxeFlexIA.",
  es: "Hola, esta es una voz femenina natural — generada por LuxeFlexIA.",
};

function landingArtistLine(name, locale) {
  const safeName = String(name || "").trim() || "LuxeFlexIA";
  if (locale === "en") {
    return `Hi, I'm ${safeName} — generated by LuxeFlexIA.`;
  }
  if (locale === "es") {
    return `Hola, me presento, soy ${safeName} — generado por LuxeFlexIA.`;
  }
  return `Salut, je me présente, c'est ${safeName} — j'ai été généré par LuxeFlexIA.`;
}

function buildLandingVoiceScript(entry, localeLike) {
  const locale = normalizeVoiceLocale(localeLike);
  if (entry?.demoKind === "natural-male") {
    return LANDING_NATURAL_MALE[locale];
  }
  if (entry?.demoKind === "natural-female") {
    return LANDING_NATURAL_FEMALE[locale];
  }
  return landingArtistLine(entry?.name, locale);
}

function buildCatalogSampleLine(name, localeLike) {
  return buildLandingVoiceScript({ name, demoKind: "artist" }, localeLike);
}

function getCatalogSampleLine(name, localeLike) {
  return buildCatalogSampleLine(name || "LuxeFlexIA", localeLike);
}

module.exports = {
  LOCALES,
  normalizeVoiceLocale,
  getCatalogSampleLine,
  buildCatalogSampleLine,
  buildLandingVoiceScript,
};
